-- Bounded context Plant Configuration (segmento industrial).
--
-- Da dueño a dos conceptos que hasta ahora eran enteros sueltos sin respaldo:
-- el puesto de trabajo y la zona de planta. Los referenciaban tres contextos
-- (occupationalhealth, personaldosimetry, aiforecasting) y ninguno los creaba,
-- así que se podía abrir un turno en un puesto inexistente y eso acababa en un
-- reporte de cumplimiento, que es registro legal a cinco años.
--
-- Topología que modela (la del segmento industrial):
--
--   Planta (= organización, una cuenta CLIENT)
--     └── Zona ──── 1 edge
--           ├── varios dispositivos IoT
--           └── varios puestos de trabajo
--
-- Notas de diseño:
--  - `plant_edges` la escribe el SSO desde el portal, declarando qué edge sirve
--    cada zona. NO la escribe el edge: el edge del segmento industrial todavía
--    no existe. Cuando exista, tendrá contra qué autenticarse.
--  - `organization_id` referencia `users(id)`, igual que en V13: la organización
--    es la cuenta CLIENT de la empresa.
--  - `AUTO_INCREMENT` por consistencia con V1→V21. El estándar
--    `GENERATED BY DEFAULT AS IDENTITY` no existe en MySQL 8, así que el paso a
--    PostgreSQL exigirá traducir estas migraciones de todos modos.

CREATE TABLE plant_zones (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    organization_id BIGINT       NOT NULL,
    name            VARCHAR(150) NOT NULL,
    description     VARCHAR(400) NULL,
    created_at      DATETIME(6)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_plant_zones_organization
        FOREIGN KEY (organization_id) REFERENCES users (id) ON DELETE RESTRICT,
    UNIQUE KEY uq_plant_zones_name (organization_id, name),
    KEY ix_plant_zones_organization (organization_id)
) ENGINE = InnoDB;

-- Un edge por zona: la UNIQUE sobre plant_zone_id es la que impone el 1 a 1.
CREATE TABLE plant_edges (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    plant_zone_id BIGINT       NOT NULL,
    serial_number VARCHAR(100) NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    created_at    DATETIME(6)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_plant_edges_zone
        FOREIGN KEY (plant_zone_id) REFERENCES plant_zones (id) ON DELETE RESTRICT,
    CONSTRAINT ck_plant_edges_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    UNIQUE KEY uq_plant_edges_zone (plant_zone_id),
    UNIQUE KEY uq_plant_edges_serial (serial_number)
) ENGINE = InnoDB;

CREATE TABLE job_positions (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    plant_zone_id BIGINT       NOT NULL,
    name          VARCHAR(150) NOT NULL,
    description   VARCHAR(400) NULL,
    created_at    DATETIME(6)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_job_positions_zone
        FOREIGN KEY (plant_zone_id) REFERENCES plant_zones (id) ON DELETE RESTRICT,
    UNIQUE KEY uq_job_positions_name (plant_zone_id, name),
    KEY ix_job_positions_zone (plant_zone_id)
) ENGINE = InnoDB;

-- ── Dispositivos: se les da zona, SIN quitarles `location` ────────────────────
-- `location` es VARCHAR libre y lo consumen 17 archivos del Front-End, 12 del
-- Mobile_App y tres DTOs (DeviceDto, CreateDeviceRequest, ReadingDto).
-- Quitarlo sería un cambio rompedor en tres repos, así que la columna se queda
-- y `plant_zone_id` se añade al lado. Se deprecia cuando los clientes migren.
ALTER TABLE devices ADD COLUMN plant_zone_id BIGINT NULL;
ALTER TABLE devices ADD CONSTRAINT fk_devices_plant_zone
    FOREIGN KEY (plant_zone_id) REFERENCES plant_zones (id) ON DELETE SET NULL;
CREATE INDEX ix_devices_plant_zone ON devices (plant_zone_id);

-- Backfill: cada (cliente, location) distinta se convierte en una zona, y el
-- dispositivo queda apuntando a ella. Conserva la agrupación que ya existía de
-- forma implícita en el texto. Los dispositivos sin cliente (los que entran por
-- `Device.unregistered`) o sin location se quedan con plant_zone_id NULL.
INSERT INTO plant_zones (organization_id, name, description, created_at)
SELECT DISTINCT d.client_id, d.location,
       'Zona creada automaticamente al migrar devices.location (V22)', NOW(6)
FROM devices d
WHERE d.client_id IS NOT NULL
  AND d.location IS NOT NULL
  AND d.location <> '';

UPDATE devices d
JOIN plant_zones z
  ON z.organization_id = d.client_id AND z.name = d.location
SET d.plant_zone_id = z.id
WHERE d.plant_zone_id IS NULL;

-- ── Integridad referencial en occupational health ─────────────────────────────
-- Hasta aquí `position_assignments.job_position_id` y `.plant_zone_id` eran
-- enteros libres. Ahora apuntan de verdad.
--
-- Antes de poner las FK hay que limpiar las filas que NO pueden satisfacerlas:
-- las sembradas por OccupationalHealthDataSeeder con ids inventados (2001, 2002
-- y zonas 1, 2). El borrado está acotado a huérfanas — si un id sí existe en las
-- tablas nuevas, la fila se conserva —, así que en un entorno con datos reales
-- es una operación vacía.
DELETE FROM position_assignments
WHERE job_position_id NOT IN (SELECT id FROM job_positions)
   OR plant_zone_id NOT IN (SELECT id FROM plant_zones);

-- Un WorkerShift sin tramos rompe su propia invariante al cargarse (el agregado
-- exige tramos contiguos), así que los turnos que se quedaron vacíos también se
-- van. El SELECT envuelto en derivada es obligatorio: MySQL no deja referenciar
-- en una subconsulta la misma tabla que se está borrando.
DELETE FROM worker_shifts
WHERE id NOT IN (
    SELECT shift_id FROM (
        SELECT DISTINCT worker_shift_id AS shift_id FROM position_assignments
    ) AS used
);

ALTER TABLE position_assignments ADD CONSTRAINT fk_position_assignments_job_position
    FOREIGN KEY (job_position_id) REFERENCES job_positions (id) ON DELETE RESTRICT;
ALTER TABLE position_assignments ADD CONSTRAINT fk_position_assignments_plant_zone
    FOREIGN KEY (plant_zone_id) REFERENCES plant_zones (id) ON DELETE RESTRICT;

